// Copies the web app (index.html + assets at the repo root) into a single
// HTML string that the phone app loads, so the app works fully offline.
// Run after every change to the web app:  npm run sync-web
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');

let html = read('index.html');
const css = read('assets/app.css');
const js = read('assets/app.js');

html = html
  .replace(/^\s*<link rel="manifest"[^>]*>\n/m, '')
  .replace(/^\s*<link rel="(icon|apple-touch-icon)"[^>]*>\n/gm, '')
  .replace('<link rel="stylesheet" href="assets/app.css">', () => `<style>\n${css}\n</style>`)
  .replace('<script src="assets/app.js"></script>', () => `<script>\n${js.replace(/<\/script/gi, '<\\/script')}\n</script>`);

if (html.includes('assets/app.')) throw new Error('Failed to inline assets. Did index.html change?');

const out = `// Generated by scripts/sync-web.js. Do not edit by hand.\nexport default ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'web', 'bundle.js'), out);
console.log('web/bundle.js updated (' + Math.round(out.length / 1024) + ' KB)');
